package com.tibyaan.runtime.spring;

import com.fasterxml.jackson.databind.ObjectMapper;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.core.io.Resource;

import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;

/**
 * Reads the generated capabilities manifest from a {@link Resource}. When the manifest is
 * absent, the runtime starts with no tools rather than failing, so adding the dependency is
 * always safe.
 *
 * <p>Since phase Binding Identity (Volume 7 section 12.2, R3) a manifest whose binding is not qualified
 * is refused at load, failing the host with a located message: such a manifest was generated by a tool
 * older than the runtime, and resolving its bindings by simple name is the defect the phase closed.
 */
public final class CapabilitiesLoader {

    private static final Logger log = LoggerFactory.getLogger(CapabilitiesLoader.class);

    private final ObjectMapper objectMapper;

    public CapabilitiesLoader(ObjectMapper objectMapper) {
        this.objectMapper = objectMapper;
    }

    public CapabilitiesManifest load(Resource resource) {
        if (resource == null || !resource.exists()) {
            log.warn("Tibyaan: no capabilities manifest found at {}; no tools will be registered", resource);
            return CapabilitiesManifest.empty();
        }
        CapabilitiesManifest manifest;
        try (InputStream in = resource.getInputStream()) {
            manifest = objectMapper.readValue(in, CapabilitiesManifest.class);
        } catch (IOException e) {
            throw new UncheckedIOException("failed to read capabilities manifest from " + resource, e);
        }
        requireQualifiedBindings(manifest, resource);
        return manifest;
    }

    // R3: every binding is <qualified class>#<method>. The first offender is named with its capability and
    // the fix; the runtime never narrows the surface silently by skipping it.
    static void requireQualifiedBindings(CapabilitiesManifest manifest, Object where) {
        for (CapabilityDescriptor tool : manifest.tools()) {
            String binding = tool.binding() == null ? "" : tool.binding();
            int hash = binding.indexOf('#');
            String className = hash < 0 ? binding : binding.substring(0, hash);
            if (hash < 0 || className.indexOf('.') < 0) {
                throw new IllegalStateException("Tibyaan: capability '" + tool.name() + "' in " + where
                        + " carries the binding '" + binding + "', which is not qualified (expected"
                        + " <qualified class>#<method>). The manifest was generated by a Tibyaan older than 0.4.0;"
                        + " regenerate it with the same Tibyaan version as this runtime (Volume 7 section 12, R3)");
            }
        }
    }
}
